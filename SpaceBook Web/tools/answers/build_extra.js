'use strict';
/* Builds js/answers_extra.js: the answers written and checked for parts the printed key has no line for, or has a wrong line for.
 *     node --max-old-space-size=6144 tools/answers/build_extra.js [--check]
 * Sources: tools/answers/src/*.json, one file per book: {book: <BOOK.title>, mcq: [{ex, q, part, letter, why, printed?, noLetter?}], leaves: [{ex, q, part, answer, why?}]}.
 * An MCQ entry takes the text of its option from the book data, so the answer always names what the student sees. Records are read by
 * js/math6_reader.js (extraRec): SB_EXTRA_ANSWERS[book title]["exercise|question|part"] = {answer, steps}. --check fails when the file is stale.
 * Dev-only, never shipped. */
const fs = require('fs'), path = require('path');
const ROOT = path.resolve(__dirname, '..', '..');
process.chdir(ROOT);
const { load } = require('../lib/app_sandbox');

const SRC = path.join(__dirname, 'src');
const OUT = path.join(ROOT, 'js', 'answers_extra.js');
const sources = fs.readdirSync(SRC).filter(f => f.endsWith('.json')).sort().map(f => JSON.parse(fs.readFileSync(path.join(SRC, f), 'utf8')));

const app = load({ page: 'lazy.html', quiet: true });
// the options of every MCQ part, by "book title|exercise|question|part"
const options = JSON.parse(app.run(`JSON.stringify((() => {
  const R = window.MATH6_READER, res = {};
  for (let n = 1; n <= 12; n++) {
    const L = window['CLS' + n + '_BOOKS']; if (!L) continue;
    Object.keys(L).forEach(k => {
      const B = L[k]; if (!B || !B.units) return;
      const title = (B.book && B.book.title) || '';
      R.withBook(B.words, B.book, () => {
        B.units.forEach(u => (u.sections || []).forEach(s => (s.blocks || []).forEach(function walk(b, exId) {
          if (!b || typeof b !== 'object') return;
          if (b.t === 'exercise') exId = String(b.id);
          if (b.t === 'q' && (b.parts || []).length) {
            const ps = b.parts;
            const labs = R.partLabels(ps);
            const opt = ps.map((p, i) => /^[a-e]$/.test(labs[i]) && labs.slice(0, i).some(x => R.isRoman(x)));
            ps.forEach((p, i) => {
              if (opt[i]) return;
              let opts = null;
              const circ = String(p.en || '').split('○');
              if (circ.length >= 4 && circ.length <= 5) opts = circ.slice(1).map(x => x.trim());
              else if (opt[i + 1]) { opts = []; for (let j = i + 1; j < ps.length && opt[j]; j++) opts.push(ps[j].en); }
              if (opts) res[title + '|' + exId + '|' + b.no + '|' + labs[i]] = opts;
            });
          }
          (b.blocks || []).forEach(x => walk(x, exId));
        })));
      });
    });
  }
  return res;
})())`));

const partKey = no => {      // same as js/math6_reader.js
  const s = String(no == null ? '' : no).trim(), m = /^\(?([A-Za-z]{1,5}|\d{1,3})(?:\)\.|\)|\.)?(?:\s|$)/.exec(s);
  return (m ? m[1] : s.replace(/[()\s.]/g, '')).toLowerCase();
};
const out = {}, problems = [], diff = [];
sources.forEach(src => {
  const book = out[src.book] = out[src.book] || {};
  (src.mcq || []).forEach(e => {
    const opts = options[src.book + '|' + e.ex + '|' + e.q + '|' + partKey(e.part)];
    if (!opts) { problems.push('no MCQ options found for ' + src.book + ' ' + e.ex + ' Q' + e.q + ' ' + e.part); return; }
    let answer;
    if (e.noLetter) answer = 'Options a, b and c are all true; d is false.';
    else {
      const idx = 'abcde'.indexOf(e.letter);
      if (idx < 0 || idx >= opts.length) { problems.push('letter ' + e.letter + ' is not an option of ' + e.ex + ' ' + e.part); return; }
      answer = e.letter + ') ' + opts[idx];
      if (e.printed && e.printed !== e.letter) diff.push(e.ex + ' ' + e.part + ': printed ' + e.printed + ', checked ' + e.letter);
    }
    book[e.ex + '|' + e.q + '|' + partKey(e.part)] = { answer, steps: e.why ? [{ en: e.why }] : [] };
  });
  (src.leaves || []).forEach(e => { book[e.ex + '|' + e.q + '|' + partKey(e.part)] = { answer: e.answer, steps: e.steps || (e.why ? [{ en: e.why }] : []) }; });
});

const sorted = Object.fromEntries(Object.keys(out).sort().map(b => [b, Object.fromEntries(Object.keys(out[b]).sort().map(k => [k, out[b][k]]))]));
const text = '// Answers written and checked for parts the printed key has no line for or gets wrong. Generated by tools/answers/build_extra.js from tools/answers/src/*.json: do not edit.\n'
  + 'window.SB_EXTRA_ANSWERS = ' + JSON.stringify(sorted) + ';\n';
if (problems.length) { console.log('FAIL  ' + problems.length + ' entries do not match the book data:\n  ' + problems.join('\n  ')); process.exit(1); }
const count = Object.values(sorted).reduce((n, b) => n + Object.keys(b).length, 0);
if (process.argv.includes('--check')) {
  const have = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : '';
  if (have !== text) { console.log('STALE  js/answers_extra.js (node tools/answers/build_extra.js)'); process.exit(1); }
  console.log('fresh  answers_extra  (' + count + ' answers)');
} else {
  fs.writeFileSync(OUT, text);
  console.log('wrote js/answers_extra.js: ' + count + ' answers in ' + Object.keys(sorted).length + ' books; printed key differs on ' + diff.length + ':');
  diff.forEach(d => console.log('  ' + d));
}

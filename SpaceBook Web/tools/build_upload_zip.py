# Builds D:\SpaceBook\deploy\spacebook_upload.zip: exactly the files the live site needs, ready to upload to
# public_html/spacebook and extract (cPanel File Manager > Upload, then Extract). api/config.php inside it points at
# the live database on wantuch.pk. The zip stays local (deploy/ is gitignored) because it holds that password.
#   python tools/build_upload_zip.py
import json, os, subprocess, zipfile

WEB = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(os.path.dirname(WEB), 'deploy', 'spacebook_upload.zip')
SITE = ['index.html', 'logo_tuitionhub_trans.png', 'css', 'js', 'assets', 'api', 'covers']
LIVE_DB = {'db_host': 'localhost', 'db_name': 'tafseelk_spacebook', 'db_user': 'tafseelk_spacebook'}

# PHP reads the local config (same password online) and writes the live one, so quoting is PHP's own
PHP_EXE = r'C:\xampp\php\php.exe'
code = ("$c = require $argv[1]; foreach (json_decode($argv[2], true) as $k => $v) $c[$k] = $v;"
        "echo \"<?php\\n// Live database (wantuch.pk). Generated by tools/build_upload_zip.py.\\nreturn \" . var_export($c, true) . \";\\n\";")
php = subprocess.run([PHP_EXE, '-r', code, os.path.join(WEB, 'api', 'config.php'), json.dumps(LIVE_DB)],
                     capture_output=True, text=True, check=True).stdout

os.makedirs(os.path.dirname(OUT), exist_ok=True)
n = 0
with zipfile.ZipFile(OUT, 'w', zipfile.ZIP_DEFLATED, compresslevel=6) as z:
    for item in SITE:
        src = os.path.join(WEB, item)
        files = [src] if os.path.isfile(src) else [os.path.join(dp, f) for dp, _, fs in os.walk(src) for f in fs]
        for f in files:
            rel = os.path.relpath(f, WEB).replace(os.sep, '/')
            if rel == 'api/config.php' or rel.startswith('api/.schema-'):
                continue
            z.write(f, rel); n += 1
    z.writestr('api/config.php', php); n += 1
print(f'{n} files -> {OUT} ({os.path.getsize(OUT)/1e6:.0f} MB)')

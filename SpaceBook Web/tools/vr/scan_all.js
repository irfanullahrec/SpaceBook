'use strict';
/* Where are worked steps, and how many can be animated safely?  node tools/vr/scan_all.js
 * Runs every js/*.js data file in a sandbox, finds objects that carry a `steps` array of strings, and applies autoSpec. */
const fs = require('fs'), path = require('path'), vm = require('vm');
const ROOT = path.resolve(__dirname, '..', '..');
const { autoSpec } = require(path.join(ROOT, 'js', 'vr_auto.js'));
const dir = path.join(ROOT, 'js');
const rows = [];
let total = 0, conv = 0;
for (const f of fs.readdirSync(dir).filter(x => /\.js$/.test(x))) {
  const raw = fs.readFileSync(path.join(dir, f), 'utf8');
  if (!/"steps"|steps:|"solution"/.test(raw) || raw.length > 40e6) continue;
  const code = raw.replace(/^(const|let) /gm, 'var ');
  const ctx = vm.createContext({ window: {}, document: {}, console: { log() {}, warn() {}, error() {} }, localStorage: {}, navigator: {}, setTimeout() {}, addEventListener() {} });
  try { vm.runInContext(code, ctx, { timeout: 8000 }); } catch (e) { /* partial globals are still scanned */ }
  let items = 0, ok = 0, seen = new Set();
  const walk = (o, d) => {
    if (!o || typeof o !== 'object' || seen.has(o) || d > 12) return; seen.add(o);
    if (Array.isArray(o.steps) && o.steps.length && o.steps.every(s => typeof s === 'string') && !/^partial/.test(o.solutionStatus || '')) { items++; if (autoSpec(o.steps).spec) ok++; }
    else if (Array.isArray(o.steps) && o.steps.length && o.steps.every(s => s && typeof s === 'object' && typeof s.en === 'string')) {
      items++; if (autoSpec(o.steps.map(s => ({ text: s.en, m: s.m || '' }))).spec) ok++;
    }
    else if (typeof o.solution === 'string' && o.solution.includes('\n') && !Array.isArray(o.steps) && !/^partial/.test(o.solutionStatus || '')) {
      const st = o.solution.split(/\n+/).map(x => x.trim()).filter(Boolean);
      if (st.length >= 2) { items++; if (autoSpec(st).spec) ok++; }
    }
    for (const k of Object.keys(o)) walk(o[k], d + 1);
  };
  for (const k of Object.keys(ctx)) { try { walk(ctx[k], 0); } catch (e) { /* ignore */ } }
  if (items) { rows.push([f, items, ok]); total += items; conv += ok; }
}
rows.sort((a, b) => b[1] - a[1]);
if (process.argv.includes('--md')) {
  const mathy = rows.filter(r => r[2] > 0 && /math|phys|chem|stat|science|computer|econ/.test(r[0]));
  const md = ['# Visual reasoning coverage', '', 'Generated by `node tools/vr/scan_all.js --md` (' + new Date().toISOString().slice(0, 10) + ').', '',
    'A worked item is **animatable** when its own steps contain at least two written rows (an equation chain it can show line by line, with what-changed highlights).',
    'Items without a safe chain keep the normal presentation; nothing is rewritten. Hand-authored specs (Class 12 Maths Unit 2, Ex 2.1 Q3-Q4): 8.', '',
    '| Data file | worked items | animatable | share |', '|---|---:|---:|---:|']
    .concat(mathy.map(r => '| ' + r[0] + ' | ' + r[1] + ' | ' + r[2] + ' | ' + Math.round(100 * r[2] / r[1]) + '% |'))
    .concat(['', '**Total: ' + total + ' worked items scanned, ' + conv + ' animatable.**', '',
      'Files with worked steps but no equation chain (prose reasoning: languages, sciences, social subjects): ' + rows.filter(r => !r[2]).length + '.',
      '', '## Not covered (by design)', '- Steps that are prose only, set notation with braces, matrices, or text the parser cannot turn into TeX with certainty.',
      '- Physics, Chemistry, Statistics and Biology banks in the data files hold almost no written worked steps (answers only): nothing to animate until worked steps exist.'])
    .join('\n');
  fs.writeFileSync(path.join(ROOT, 'docs', '09_VR_COVERAGE.md'), md + '\n');
  console.log('wrote docs/09_VR_COVERAGE.md');
} else rows.forEach(r => console.log(r[0].padEnd(34), String(r[1]).padStart(5), String(r[2]).padStart(5)));
console.log('TOTAL worked items', total, 'animatable', conv);

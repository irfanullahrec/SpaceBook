'use strict';
/* Lexicon coverage report and review queues (Phase 7).
 *   node --max-old-space-size=8192 tools/build/lexicon_report.js            prints the report
 *   node --max-old-space-size=8192 tools/build/lexicon_report.js --write    writes docs/LEXICON_COVERAGE.md and docs/lexicon_review/*.csv
 * For every distinct word of the books (the lists of js/word_stats_words.js, with how often each occurs) it asks the device lexicon what the
 * word means in each other language (SBOfflineLookup: Lexicon v1 + the English-Urdu dictionary), per class and per language pair, and lists
 * the most frequent words without a meaning: those are the review queues for the people who translate. Words are counted as types (each
 * distinct word once) and weighted by how often the word occurs in the books. Dev-only. */
const fs = require('fs'), path = require('path');
const { load, ROOT } = require('../lib/app_sandbox');
const WRITE = process.argv.includes('--write');
// tokens that came from the transcription and code samples, not from the language: they stay out of the review queues
const NOISE = new Set(['scan', 'pdf', 'ul', 'kptbb', 'svg', 'rs', 'co', 'int', 'fig', 'obscured', 'unresolved', 'watermark', 'eq', 'ye', 'km', 'cos', 'cout', 'ac', 'html', 'abc', 'src', 'img', 'div', 'span', 'td', 'tr', 'th', 'br', 'nbsp', 'px', 'em', 'rem', 'href', 'cin', 'int', 'printf', 'scanf', 'endl', 'std', 'iostream']);

// ---- the word lists and who uses them
const W = {}; new Function('window', fs.readFileSync(path.join(ROOT, 'js', 'word_stats_words.js'), 'utf8'))(W);
const D = W.SB_WORD_STATS_WORDS;
const LANGS = ['en', 'ur', 'ps', 'ar'], NAME = { en: 'English', ur: 'Urdu', ps: 'Pashto', ar: 'Arabic' };
const words = {}, freq = {}, members = {};
for (const L of LANGS) {
  words[L] = D.words[L].split('\n');
  freq[L] = D.freq[L].split(',').map(x => parseInt(x, 36));
  members[L] = {};
  for (const scope of Object.keys(D.scopes)) {
    const enc = D.scopes[scope] && D.scopes[scope][L];
    if (!enc) continue;
    let prev = -1; const out = [];
    for (const part of enc.split(',')) { prev += parseInt(part, 36); out.push(prev); }
    members[L][scope] = out;
  }
}

// ---- ask the device lexicon, once per (word, other language)
const app = load({ page: 'lazy.html', quiet: true });
const have = {};          // have[src][tgt] = Uint8Array(words)
for (const src of LANGS) {
  have[src] = {};
  for (const tgt of LANGS) {
    if (src === tgt) continue;
    const list = JSON.stringify(words[src]);
    const out = JSON.parse(app.run(`(() => { const w = ${list}; const o = new Array(w.length); for (let i = 0; i < w.length; i++) { let r = ''; try { r = SBOfflineLookup(w[i], '${src}', '${tgt}'); } catch (e) { r = ''; } o[i] = r ? 1 : 0; } return JSON.stringify(o); })()`, 1200000));
    have[src][tgt] = out;
  }
}

const pct = (a, b) => b ? (100 * a / b).toFixed(1) + ' %' : '-';
function coverage(src, tgt, idxs) {
  const h = have[src][tgt]; let n = 0, k = 0, tn = 0, tk = 0;
  for (const i of idxs) { n++; tn += freq[src][i]; if (h[i]) { k++; tk += freq[src][i]; } }
  return { types: n, typesHit: k, tokens: tn, tokensHit: tk };
}
const all = L => words[L].map((_, i) => i);

const lines = [];
lines.push('# Lexicon coverage');
lines.push('');
lines.push('Generated by `node tools/build/lexicon_report.js --write` from the word lists of the books (`js/word_stats_words.js`) and the device lexicon (`js/lexicon_data.js` + the English-Urdu dictionary). A word "has a meaning" when a lookup in that direction returns one. **Types** = distinct words; **tokens** = occurrences in the books (a missing common word hurts more than a missing rare one). The numbers describe what a student gets offline today; nothing here is machine translation.');
lines.push('');
lines.push('Lexicon: ' + (app.run('SB_LEXICON_V1.rows.length')) + ' rows; word lists: ' + LANGS.map(L => NAME[L] + ' ' + words[L].length).join(', ') + ' distinct words.');
lines.push('');
lines.push('## Whole project, by direction');
lines.push('');
lines.push('| From | To | Words with a meaning (types) | Occurrences covered (tokens) |');
lines.push('|---|---|---|---|');
const proj = {};
for (const src of LANGS) for (const tgt of LANGS) if (src !== tgt) { const c = coverage(src, tgt, all(src)); proj[src + '>' + tgt] = c; lines.push(`| ${NAME[src]} | ${NAME[tgt]} | ${c.typesHit} of ${c.types} (${pct(c.typesHit, c.types)}) | ${pct(c.tokensHit, c.tokens)} |`); }
lines.push('');
lines.push('The owner target for Phase 7 is >= 95 % of tokens for English <-> Urdu <-> Pashto and >= 85 % for Arabic. Where a direction is far from it, the review queues below say which words to translate first.');
lines.push('');
lines.push('## By class (English words: types / tokens with an Urdu, Pashto and Arabic meaning)');
lines.push('');
lines.push('| Class | English words | Urdu | Pashto | Arabic |');
lines.push('|---|---|---|---|---|');
const classScopes = Object.keys(D.scopes).filter(s => /^cls\d+$/.test(s)).sort((a, b) => parseInt(a.slice(3), 10) - parseInt(b.slice(3), 10));
for (const sc of classScopes) {
  const idx = members.en[sc] || [];
  if (!idx.length) continue;
  const cells = ['ur', 'ps', 'ar'].map(t => { const c = coverage('en', t, idx); return `${pct(c.typesHit, c.types)} / ${pct(c.tokensHit, c.tokens)}`; });
  lines.push(`| ${sc.replace('cls', 'Class ')} | ${idx.length} | ${cells.join(' | ')} |`);
}
lines.push('');

// ---- review queues
const QUEUES = [['en', 'ur'], ['en', 'ps'], ['en', 'ar'], ['ur', 'en'], ['ps', 'en'], ['ar', 'en']];
const outDir = path.join(ROOT, 'docs', 'lexicon_review');
if (WRITE) fs.mkdirSync(outDir, { recursive: true });
lines.push('## Review queues (most frequent words without a meaning first)');
lines.push('');
lines.push('One CSV per direction in `docs/lexicon_review/` (rank, word, occurrences in the books, classes that use it). A translator fills the target column; the filled rows become reviewed lexicon entries. Machine suggestions may be added only as `machine`, never as reviewed.');
lines.push('');
for (const [src, tgt] of QUEUES) {
  const h = have[src][tgt];
  const order = all(src).filter(i => !h[i] && words[src][i].length > 1 && !(src === 'en' && NOISE.has(words[src][i]))).sort((a, b) => freq[src][b] - freq[src][a]).slice(0, 2000);
  const classUse = {};
  for (const sc of classScopes) for (const i of (members[src][sc] || [])) (classUse[i] = classUse[i] || []).push(sc.replace('cls', ''));
  const csv = ['rank,word,occurrences,classes,' + tgt + '_meaning'].concat(order.map((i, r) => [r + 1, JSON.stringify(words[src][i]), freq[src][i], JSON.stringify((classUse[i] || []).join(' ')), ''].join(','))).join('\n') + '\n';
  const file = `${src}_to_${tgt}.csv`;
  if (WRITE) fs.writeFileSync(path.join(outDir, file), csv);
  const missing = all(src).filter(i => !h[i]).length;
  lines.push(`- **${NAME[src]} -> ${NAME[tgt]}**: ${missing} words without a meaning; the top ${order.length} are in \`docs/lexicon_review/${file}\` (they cover ${pct(order.reduce((n, i) => n + freq[src][i], 0), coverage(src, tgt, all(src)).tokens)} of all occurrences).`);
}
lines.push('');
const report = lines.join('\n') + '\n';
if (WRITE) { fs.writeFileSync(path.join(ROOT, 'docs', 'LEXICON_COVERAGE.md'), report); console.log('wrote docs/LEXICON_COVERAGE.md and ' + QUEUES.length + ' review queues'); }
console.log(report.split('\n').slice(0, 24).join('\n'));

/* Build js/<subject>12_exercise_banks.js from parsed source questions + authored answers.
 * Answers: tools/class12_answers/<subject>/u<N>.json
 *   {"mcqs":[["B","step",...] | {"c":"B","s":[...],"a":"final","n":"note"}], "shortQuestions":[["step",...] | {...}], ...}
 *   MCQ letter "-" means no printed choice is fully correct (explain in n).
 * usage: node tools/class12_exercise_build.cjs <subject> */
const fs = require('fs'), path = require('path');
const {parseUnit} = require('./class12_exercise_parse.cjs');
const ROOT = path.resolve(__dirname, '..');
const subject = process.argv[2];
const runtime = {window: {}}; require('vm').createContext(runtime);
require('vm').runInContext(fs.readFileSync(path.join(ROOT, 'js/class12_exercise_banks.js'), 'utf8'), runtime);
const TX = runtime.window.class12ExerciseText;
const {load} = require('./class12_exercise_parse.cjs');
const dir = path.join(ROOT, 'tools/class12_answers', subject);
const specs = {}, problems = [], warnings = [];
for (const file of fs.readdirSync(dir).filter(f => /^u\d+\.json$/.test(f)).sort()) {
  const unit = file.match(/\d+/)[0];
  const answers = JSON.parse(fs.readFileSync(path.join(dir, file), 'utf8'));
  const {out} = parseUnit(subject, unit);
  const items = {};
  for (const [cat, list] of Object.entries(out)) {
    const given = answers[cat] || [];
    if (!list.length && !given.length) continue;
    if (given.length !== list.length) { problems.push(`u${unit} ${cat}: ${list.length} questions, ${given.length} answers`); continue; }
    items[cat] = list.map((q, i) => {
      let a = given[i];
      if (Array.isArray(a)) a = cat === 'mcqs' ? {c: a[0], s: a.slice(1)} : {s: a};
      if (!a.s || !a.s.length || a.s.some(x => typeof x !== 'string' || !x.trim())) problems.push(`u${unit} ${cat} ${i + 1}: empty answer`);
      const rec = {q: q.q.map(r => [r.sectionId, r.index]), s: a.s};
      if (a.a) rec.a = a.a;
      if (a.n) rec.n = a.n;
      if (a.d) rec.d = a.d; // source figure block id shown with the question
      if (q.printedAnswer) rec.p = [q.printedAnswer.sectionId, q.printedAnswer.index];
      if (cat === 'mcqs') {
        if (q.options.length === 1) { q.q.push(...q.options); q.options = []; rec.q = q.q.map(r => [r.sectionId, r.index]); } // one paragraph holds all choices
        let count = q.options.length;
        if (count) rec.o = q.options.map(r => [r.sectionId, r.index]);
        else {
          rec.inline = 1;
          const ch = load(subject).find(c => String(c.number) === unit);
          const fix = text => (a.r || []).reduce((t, [from, to, nth = 1]) => { let at = -1; for (let k = 0; k < nth; k++) { at = t.indexOf(from, at + 1); if (at < 0) return t; } return t.slice(0, at) + to + t.slice(at + from.length); }, text); // [from, to, nth]: replace the nth occurrence
          const joined = f => fix(q.q.map(r => TX.stripNumber(ch.sections.find(s => s.id === r.sectionId).paras[r.index][f] || '')).join(' '));
          if (a.r) rec.r = a.r;
          const en = TX.splitInline(joined('text'));
          count = en ? en.options.length : 0;
          for (const f of ['urdu', 'pashto']) if (joined(f) && !TX.splitInline(joined(f), true)) warnings.push(`u${unit} mcq ${i + 1}: ${f} choices not split`);
        }
        if (count < 2) problems.push(`u${unit} mcq ${i + 1}: ${count} options`);
        const nOptions = count;
        if (a.c !== '-') {
          const c = String(a.c || '').toUpperCase().charCodeAt(0) - 65;
          if (!(c >= 0 && c < nOptions)) problems.push(`u${unit} mcq ${i + 1}: bad letter ${a.c}`);
          rec.c = c;
        } else if (!a.n) problems.push(`u${unit} mcq ${i + 1}: "-" needs a note`);
      }
      return rec;
    });
  }
  specs[unit] = {items};
}
if (warnings.length) console.warn(warnings.join('\n'));
if (problems.length) { console.error(problems.join('\n')); process.exit(1); }
const outFile = path.join(ROOT, 'js', subject + '12_exercise_banks.js');
fs.writeFileSync(outFile, `/* Generated by tools/class12_exercise_build.cjs from tools/class12_answers/${subject}/ — do not edit by hand. */\nregisterClass12ExerciseBanks(${JSON.stringify(subject)}, ${JSON.stringify(specs)});\n`);
console.log('wrote', path.relative(ROOT, outFile), Object.entries(specs).map(([u, s]) => u + ':' + Object.entries(s.items).map(([k, v]) => k[0] + v.length).join('')).join(' '));

# Helper to slice paras by line contents
def get_paras_slice(paras, start_kw, end_kw=None):
    start_idx = 0
    found_start = False
    for i, p in enumerate(paras):
        if start_kw in p:
            start_idx = i
            found_start = True
            break
    if not found_start:
        return []
    if end_kw is None:
        return paras[start_idx:]
    end_idx = len(paras)
    for j in range(start_idx + 1, len(paras)):
        if end_kw in paras[j]:
            end_idx = j
            break
    return paras[start_idx:end_idx]


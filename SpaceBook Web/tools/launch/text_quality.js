'use strict';
/* A scan of the typed book pages for the faults a reader would see: broken encoding (mojibake, the replacement character), characters from a font's private area,
 * control characters, stray Latin letters inside Arabic-script words, runs of symbols, empty pages and pages that repeat another page of the same book.
 *   node tools/launch/text_quality.js [--json docs/launch/text_quality.json] [--md docs/launch/TEXT_QUALITY.md] [--check]
 * --check exits 1 when a book has more of a "hard" fault (mojibake, replacement character, private-use or control character) than the committed baseline
 * (tools/launch/text_quality_baseline.json); the softer faults are listed, not enforced. Reads docs/source-verification/class-*\/<book>/pages/p*.txt. Dev-only, never shipped. */
const fs = require('fs'), path = require('path'), crypto = require('crypto');
const ROOT = path.resolve(__dirname, '..', '..');
const SV = path.join(ROOT, 'docs', 'source-verification');
const args = process.argv.slice(2);
const opt = n => (args.includes(n) ? args[args.indexOf(n) + 1] : null);
const BASE = path.join(__dirname, 'text_quality_baseline.json');

const HARD = [
  ['mojibake', /Ã[\u0080-¿]|Â[ -¿]|â€[\u0080-¿‘-”™]|ï¿½|Ø[§-¿]|Ù[\u0080-¿]/],
  ['replacement character', /�/],
  ['private-use character', /[-]/],
  ['control character', /[\u0000-\u0008\u000B\u000C\u000E-\u001F\u007F-\u009F]/],
];
const SOFT = [
  ['Latin letter inside an Arabic-script word', /[؀-ۿݐ-ݿ][A-Za-z][؀-ۿݐ-ݿ]/],
  ['run of symbols', /[|\\\/<>~^`]{4,}|[^\w\s؀-ۿ.,;:!?()\[\]{}'"“”‘’\-–—_=+*%$#@&°²³¼½¾×÷±√∑∫πθα-ωΑ-Ω⁰-₟←-⇿∀-⋿■-◿☀-➿…•·●■□✓✗→←↑↓]{6,}/],
  ['same word repeated four times', /\b(\w{3,})\s+\1\s+\1\s+\1\b/i],
];
const books = [];
for (const cls of fs.readdirSync(SV).filter(d => /^class-\d+$/.test(d))) for (const b of fs.readdirSync(path.join(SV, cls))) {
  const dir = path.join(SV, cls, b, 'pages');
  if (fs.existsSync(dir)) books.push({ id: cls.replace('class-', 'c') + ':' + b, dir });
}
const report = {};
for (const bk of books) {
  const r = { pages: 0, empty: [], dup: [], hard: {}, soft: {}, examples: [] };
  const hashes = new Map();
  for (const f of fs.readdirSync(bk.dir).filter(x => /^p\d+\.txt$/.test(x)).sort()) {
    r.pages++;
    const raw = fs.readFileSync(path.join(bk.dir, f), 'utf8');
    const lines = raw.split(/\r?\n/);
    const body = lines.filter(l => l.trim() && !/^@/.test(l));
    const text = body.join('\n');
    const status = ((raw.match(/^@status\s+(\S+)/m) || [])[1]) || 'none';
    // a page that says why it has no text: a blank page, a duplicate scan, front or back matter, a picture page described by @deco
    const explained = /^(blank|duplicate|front-matter|back-matter|cover|missing)$/.test(status) || /^@(deco|issue|note)\s/m.test(raw);
    if (body.length === 0 || text.replace(/\s+/g, '').length < 6) { if (!explained) r.empty.push(f); }
    else if (!explained && body.length > 3) {
      const h = crypto.createHash('md5').update(text).digest('hex');
      if (hashes.has(h)) r.dup.push(f + '=' + hashes.get(h)); else hashes.set(h, f);
    }
    lines.forEach((l, i) => {
      if (/^(svg|<svg|path|d=)/.test(l.trim()) || l.length > 6000) return;           // drawings are not text
      for (const [k, rx] of HARD) if (rx.test(l)) { r.hard[k] = (r.hard[k] || 0) + 1; if (r.examples.length < 6) r.examples.push(`${f}:${i + 1} ${k}: ${l.slice(0, 90)}`); }
      for (const [k, rx] of SOFT) if (rx.test(l)) r.soft[k] = (r.soft[k] || 0) + 1;
    });
  }
  report[bk.id] = r;
}
const hardOf = r => Object.values(r.hard).reduce((a, b) => a + b, 0);
const tot = { books: books.length, pages: 0, empty: 0, dup: 0, hard: 0, soft: 0 };
for (const r of Object.values(report)) { tot.pages += r.pages; tot.empty += r.empty.length; tot.dup += r.dup.length; tot.hard += hardOf(r); tot.soft += Object.values(r.soft).reduce((a, b) => a + b, 0); }
const jf = opt('--json'); if (jf) fs.writeFileSync(path.resolve(ROOT, jf), JSON.stringify({ totals: tot, report }, null, 1) + '\n');
const mf = opt('--md');
if (mf) {
  const md = ['# Text quality scan of the typed book pages', '', 'Generated by `node tools/launch/text_quality.js --md docs/launch/TEXT_QUALITY.md`. It reads every typed page (`docs/source-verification/class-*/<book>/pages/p*.txt`) and looks for faults a reader would see. It cannot tell a wrong word from a right one: it finds broken text, not mistyped text.', '',
    `**${tot.books} books, ${tot.pages.toLocaleString('en')} pages.** Hard faults (broken encoding, replacement or private-use or control characters): **${tot.hard}**. Pages with no text and no reason given (not blank, duplicate, front or back matter, nor a picture page described by @deco): ${tot.empty}. Pages identical to another page of the same book: ${tot.dup}. Soft findings (stray Latin letters inside Arabic-script words, runs of symbols, a word repeated four times): ${tot.soft}.`, '',
    '| Book | Pages | Hard faults | Unexplained empty pages | Repeated pages | Soft findings |', '|---|---|---|---|---|---|'];
  for (const [id, r] of Object.entries(report).sort()) {
    const soft = Object.values(r.soft).reduce((a, b) => a + b, 0);
    if (hardOf(r) || r.empty.length || r.dup.length || soft) md.push(`| ${id} | ${r.pages} | ${hardOf(r)} | ${r.empty.length}${r.empty.length ? ' (' + r.empty.slice(0, 4).join(', ') + (r.empty.length > 4 ? ', ...' : '') + ')' : ''} | ${r.dup.length}${r.dup.length ? ' (' + r.dup.slice(0, 3).join(', ') + (r.dup.length > 3 ? ', ...' : '') + ')' : ''} | ${soft} |`);
  }
  md.push('', 'Books not listed have none of these faults.', '');
  fs.writeFileSync(path.resolve(ROOT, mf), md.join('\n'));
}
console.log(`text quality: ${tot.books} books, ${tot.pages} pages; hard faults ${tot.hard}, empty pages ${tot.empty}, repeated pages ${tot.dup}, soft findings ${tot.soft}`);
if (args.includes('--update-baseline')) { fs.writeFileSync(BASE, JSON.stringify(Object.fromEntries(Object.entries(report).map(([k, r]) => [k, hardOf(r)])), null, 1) + '\n'); console.log('baseline written'); }
if (args.includes('--check')) {
  const base = fs.existsSync(BASE) ? JSON.parse(fs.readFileSync(BASE, 'utf8')) : {};
  const bad = Object.entries(report).filter(([k, r]) => hardOf(r) > (base[k] || 0)).map(([k, r]) => `${k}: ${hardOf(r)} (baseline ${base[k] || 0})`);
  if (bad.length) { console.log('FAIL  more hard faults than the baseline in: ' + bad.join('; ')); process.exit(1); }
  console.log('no book has more hard faults than the baseline');
}
if (!args.includes('--quiet')) for (const [id, r] of Object.entries(report)) for (const e of r.examples.slice(0, 2)) console.log('  ' + id + ' ' + e);

'use strict';
/* Writes docs/launch/ANSWERS_WRITTEN.md: which answers SpaceBook wrote for the exercises the textbooks print without an answer, what is still open, and which
 * written answers carry a "check with the teacher" note because the printed question or data is unclear.
 *   node tools/launch/answers_written_report.js
 * Reads docs/launch/EXERCISE_COVERAGE.json (node tools/launch/exercise_coverage.js first) and the page files. Dev-only, never shipped. */
const fs = require('fs'), path = require('path');
const ROOT = path.resolve(__dirname, '..', '..');
const cov = JSON.parse(fs.readFileSync(path.join(ROOT, 'docs', 'launch', 'EXERCISE_COVERAGE.json'), 'utf8'));
const SV = path.join(ROOT, 'docs', 'source-verification');

const NOTE = /استاد سے تصدیق|check with the teacher|ask the teacher|استاذ سے تصدیق/i;
const flagged = [];
for (const cls of fs.readdirSync(SV).filter(d => /^class-\d+$/.test(d))) {
  for (const book of fs.readdirSync(path.join(SV, cls))) {
    const dir = path.join(SV, cls, book, 'pages');
    if (!fs.existsSync(dir)) continue;
    for (const f of fs.readdirSync(dir).filter(x => /^p\d+\.txt$/.test(x))) {
      const L = fs.readFileSync(path.join(dir, f), 'utf8').split(/\r?\n/);
      for (let i = 0; i < L.length; i++) {
        if (!/^(sol|ss)\s/.test(L[i]) || !NOTE.test(L[i])) continue;
        let q = '';
        for (let k = i - 1; k >= 0 && k > i - 8; k--) if (/^qp?\s/.test(L[k])) { q = L[k].split(' || ')[0].replace(/^qp?\s+\S*\s*\|\s?/, ''); break; }
        flagged.push({ book: cls.replace('class-', 'Class ') + ' ' + book, page: f.replace(/\.txt$/, ''), q: q.slice(0, 110), a: L[i].replace(/^(sol|ss)\s+/, '').slice(0, 140) });
      }
    }
  }
}

const rows = cov.books.filter(b => b.written || b.none);
const t = cov.totals;
const md = [];
md.push('# Answers written for exercises the textbooks leave unanswered', '');
md.push('Generated by `node tools/launch/answers_written_report.js` from `EXERCISE_COVERAGE.json` and the page files. An answer written by SpaceBook is stored beside its question in the page file (`sol` line), is rebuilt with the book and is shown in the app with the note "SpaceBook answer, not printed in the textbook"; the printed question text is never changed.', '');
md.push('## Totals', '');
md.push('| Questions | With an answer | Of which printed key | Of which written by SpaceBook | Still without an answer | Open MCQs (answer matches no option) |', '|---|---|---|---|---|---|');
md.push(`| ${t.questions} | ${t.ans + t.viaQ + t.key + t.written} | ${t.key} | ${t.written} | **${t.none}** | ${t.mcqOpen} |`, '');
md.push('Before the launch pass 4,652 questions had no answer (45,581 counted). "Open MCQs" are mostly lists of parts written like options, not real multiple-choice questions; the ones that are real are shown by the app as plain questions with an Ans button.', '');
md.push('## Still without an answer', '', '| Book | Questions without an answer | Why |', '|---|---|---|');
const WHY = {
  'cls5:math': 'drawing and measuring tasks (construct a quadrilateral, draw an angle) and fragments of a table whose stem is a figure',
  'cls6:math': 'sets to be written in roster form, descriptions to be matched to a figure, and fragments of a table',
  'cls7:math': 'drawing, graph, symmetry and plotting tasks that depend on a printed figure; they need a drawn model answer, not text',
  'cls8:math': 'Review Exercise 1 Q1 b): the printed key gives two right options (iii and iv); the coverage tool cannot score a question with two right options, the key and a solution state both',
  'cls10:urdu': 'the printed pages that hold the passage are missing from the scans (cannot be answered without the text)'
};
for (const b of rows.filter(b => b.none)) md.push(`| ${b.name} (${b.book}) | ${b.none} | ${WHY[b.book] || ''} |`);
md.push('', 'These stay on the list of known gaps (docs/launch/FINDINGS_REGISTER.md); none of them is hidden: the coverage tool fails the build if the number grows.', '');
// answers added to page files in the launch pass = "sol" lines added since the baseline commit (git diff against it, working tree included)
const BASE = process.env.SB_BASE || 'a0773486';
const diff = require('child_process').execFileSync('git', ['diff', '-U0', BASE, '--', 'docs/source-verification'], { cwd: ROOT, encoding: 'utf8', maxBuffer: 1 << 29 });
const authored = {};
let cur = null;
for (const l of diff.split('\n')) {
  const m = /^\+\+\+ "?b\/(?:SpaceBook Web\/)?docs\/source-verification\/(class-\d+)\/([^/]+)\/pages\//.exec(l);
  if (m) { cur = m[1].replace('class-', 'Class ') + ' ' + m[2]; continue; }
  if (l.startsWith('+++ ')) { cur = null; continue; }
  if (cur && /^\+sol\s/.test(l)) authored[cur] = (authored[cur] || 0) + 1;
}
const total = Object.values(authored).reduce((a, b) => a + b, 0);
md.push(`## Answers written in this pass, per book (${total} \`sol\` lines added to page files since ${BASE})`, '', '| Book | Answers added or rewritten |', '|---|---|');
for (const [k, v] of Object.entries(authored).sort((a, b) => b[1] - a[1])) md.push(`| ${k} | ${v} |`);
md.push('', 'Books whose answers come from the printed key or from the Maths solution generators (Classes 9 and 10 Mathematics, Class 12 Statistics key, Classes 5 to 8 Mathematics) are counted in `EXERCISE_COVERAGE.md`, not here.', '');
md.push('', `## Answers that carry a "check with the teacher" note (${flagged.length})`, '', 'The printed question or its data is blurred, misprinted or has no matching option in the scan, so the answer states what was assumed.', '', '| Book | Page | Question | Answer (start) |', '|---|---|---|---|');
for (const f of flagged) md.push(`| ${f.book} | ${f.page} | ${f.q.replace(/\|/g, '/')} | ${f.a.replace(/\|/g, '/')} |`);
md.push('');
fs.writeFileSync(path.join(ROOT, 'docs', 'launch', 'ANSWERS_WRITTEN.md'), md.join('\n'));
console.log(`docs/launch/ANSWERS_WRITTEN.md: ${rows.length} books, ${flagged.length} answers with a note`);

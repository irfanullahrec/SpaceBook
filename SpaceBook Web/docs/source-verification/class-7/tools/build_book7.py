"""Build a Class 7 (non-Mathematics) textbook from its page-by-page transcriptions.

    python tools/build_book7.py SUBJ   (SUBJ: eng, sci, urdu, comp, geo, hist, isl, quran, arabic, drawing, hpe)

Same page syntax, builder and reader as the Class 6 books (class-6/tools/build_book6.py); only the paths,
dataset names and the registry (window.CLS7_BOOKS, rendered by js/cls6_book_reader.js for classId 'cls7') differ.
Pages: class-7/<SUBJ>/pages/pNNN.txt   Scans: D:/SpaceBook/_cls7_jpg/<SUBJ>/NNN.jpg (tools/link_scans.py)
"""
from pathlib import Path
import json, sys, datetime

HERE = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(HERE.parent / 'class-6' / 'tools'))
import build_math6 as bm
import build_book6 as b6

APP = HERE.parents[2]
b6.HERE = HERE                     # load_units / load_vocab / ocr_recall read class-7/<subj>/...
JPG_ROOT = Path('D:/SpaceBook/_cls7_jpg')
SUBJECTS = {
    'eng': ('English', 'english_7_data.js', 'ENGLISH_7_DATA', 'English 7 (KPTBB, NC 2022)'),
    'sci': ('General Science', 'general_science_7_data.js', 'GENERAL_SCIENCE_7_DATA', 'General Science 7 (KPTBB, NC 2022)'),
    'urdu': ('Urdu', 'urdu_7_data.js', 'URDU_7_DATA', 'Urdu 7 (KPTBB, NC 2022)'),
    'comp': ('Computer Science', 'computer_7_data.js', 'COMPUTER_7_DATA', 'Computer Science 7 (KPTBB, NC 2022)'),
    'geo': ('Geography', 'geography_7_data.js', 'GEOGRAPHY_7_DATA', 'Geography 7 (KPTBB, NC 2022)'),
    'hist': ('History', 'history_7_data.js', 'HISTORY_7_DATA', 'History 7 (KPTBB, NC 2022)'),
    'isl': ('Islamiat', 'islamiat_7_data.js', 'ISLAMIAT_7_DATA', 'Islamiat 7 (KPTBB, NC 2022)'),
    'quran': ('Mutalia-e-Quran', 'mutalia_quran_7_data.js', 'MUTALIA_QURAN_7_DATA', 'Mutalia-e-Quran 7 (KPTBB, NC 2022)'),
    'arabic': ('Arabic', 'arabic_7_data.js', 'ARABIC_7_DATA', 'Arabic 7 (KPTBB, NC 2022)'),
    'drawing': ('Drawing', 'drawing_7_data.js', 'DRAWING_7_DATA', 'Drawing 7 (KPTBB, NC 2022)'),
    'hpe': ('Health & Physical Education', 'hpe_7_data.js', 'HPE_7_DATA', 'Health & Physical Education 7 (KPTBB, NC 2022)'),
}


def main():
    subj = sys.argv[1]
    name, legacy_file, global_name, title = SUBJECTS[subj]
    total = len(list((JPG_ROOT / subj).glob('[0-9][0-9][0-9].jpg')))
    titles, starts, labels = b6.load_units(subj)
    b = b6.BookBuilder(titles, starts)
    files = sorted((HERE / subj / 'pages').glob('p[0-9][0-9][0-9].txt'))
    for expected, f in enumerate(files):
        if int(f.stem[1:]) != expected:
            raise SystemExit(f'pages must be consecutive: expected p{expected:03}.txt, found {f.name}')
        b.page(expected, f.read_text(encoding='utf-8'))
    if b.stack:
        print('note: open container carried past last reviewed page:', b.stack[-1]['t'])
    solutions = {}

    def extract(list_):
        for x in list_:
            for owner in ([x] if x.get('t') == 'q' else []) + (x.get('parts') or []):
                if owner.get('sol'):
                    sid = f'c7{subj}-s{len(solutions) + 1}'
                    solutions[sid] = owner.pop('sol')
                    owner['solId'] = sid
            if x.get('blocks'):
                extract(x['blocks'])
    units = [b.units[n] for n in sorted(b.units)]
    for u in units:
        for s_ in u['sections']:
            extract(s_['blocks'])
    words = b6.load_vocab(subj)
    for m in b.ledger:
        m['ocrWordRecall'] = None if m['status'] in ('duplicate', 'blank', 'answers') else b6.ocr_recall(subj, m['pdfPage'] - 1, m['english'])
        m.pop('english')
    for u in units:
        if u['number'] in labels:
            u['order'], u['number'] = u['number'], labels[u['number']]
        u['reviewStatus'] = {'reviewedPdfPages': len(u['sourcePdfPages'])}
        for s in u['sections']:
            paras = [x.get('en', '') for x in s['blocks'] if x['t'] in ('h', 'p')]
            s['heading'] = s['title']
            s['headingUrdu'] = s['titleUrdu']
            s['paras'] = paras
            s['text'] = '\n\n'.join(paras)[:6000]
    reviewed = len(b.ledger)
    book = {'subject': subj, 'name': name, 'title': title, 'source': str(JPG_ROOT / subj), 'totalPdfPages': total,
            'reviewedPdfPages': reviewed, 'frontMatter': b.front, 'backMatter': b.back, 'answers': b.answers,
            'answerPdfPages': b.answer_pages, 'complete': reviewed >= total}
    js = [f'// Class 7 {name} (KPTBB) — generated by docs/source-verification/class-7/tools/build_book7.py {subj}',
          '// Source-reviewed page by page; edit the page transcriptions, not this file.',
          f'const {global_name} = ' + json.dumps(units, ensure_ascii=False) + ';',
          'if (typeof window !== "undefined") {',
          f'  window.{global_name} = {global_name};',
          '  window.CLS7_BOOKS = window.CLS7_BOOKS || {};',
          f'  window.CLS7_BOOKS[{json.dumps(subj)}] = {{units: {global_name}, book: ' + json.dumps(book, ensure_ascii=False) + ', words: ' + json.dumps(words, ensure_ascii=False) + '};',
          '  window.CLS6_SOLUTIONS = Object.assign(window.CLS6_SOLUTIONS || {}, ' + json.dumps(solutions, ensure_ascii=False) + ');',
          '}', '']
    out = APP / 'js' / legacy_file
    out.write_text('\n'.join(js), encoding='utf-8')
    (HERE / subj / 'ledger.json').write_text(json.dumps(b.ledger, ensure_ascii=False, indent=1) + '\n', encoding='utf-8')
    with (HERE / subj / 'timing.log').open('a', encoding='utf-8') as tl:
        tl.write(datetime.datetime.now().isoformat(timespec='seconds') + '\t' + str(reviewed) + '\n')
    low = [(m['pdfPage'] - 1, m['ocrWordRecall']) for m in b.ledger if m['ocrWordRecall'] is not None and m['ocrWordRecall'] < 0.85]
    untr = [(m['pdfPage'] - 1, m['untranslated'][:3]) for m in b.ledger if m['untranslated']]
    print(f'{subj}: reviewed {reviewed}/{total} pages; {len(units)} units; vocab {len(words)}; answers {len(solutions)}; {out.name} {out.stat().st_size} bytes')
    if low:
        print('LOW OCR RECALL (scan idx, recall):', low)
    if untr:
        print('UNTRANSLATED:', untr)


if __name__ == '__main__':
    main()

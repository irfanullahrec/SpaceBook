const fs=require('fs'), vm=require('vm'),path=require('path');
const root=path.resolve(__dirname,'../../..');
const context={DATA:{phys10Chapters:[{num:10,topics:[{num:'10.1'}]}]}};
vm.createContext(context);
vm.runInContext(fs.readFileSync(path.join(root,'js/physics_10_source_data.js'),'utf8'),context);
const ch=context.DATA.phys10Chapters[0];
const out=path.join(root,'tmp/class-10-physics');
fs.writeFileSync(path.join(out,'shock-coded.svg'),ch.sourceOpening.diagramSvg);
fs.writeFileSync(path.join(out,'figure10-1-coded.svg'),ch.topics[0].sourceFigure.svg);
const shm=ch.topics.find(t=>t.num==='10.2');
fs.writeFileSync(path.join(out,'figure10-2-coded.svg'),shm.sourceAside.figure.svg);
fs.writeFileSync(path.join(out,'ecg-coded.svg'),shm.sourceAside.ecg.svg);
fs.writeFileSync(path.join(out,'figure10-4-coded.svg'),ch.workedExamples.find(e=>e.sourceNumber==='10.2').figure.svg);
fs.writeFileSync(path.join(out,'figure10-3-coded.svg'),ch.topics.find(t=>t.num==='10.3').sourcePrefixFigure.svg);
fs.writeFileSync(path.join(out,'figure10-5-coded.svg'),ch.topics.find(t=>t.num==='10.4').sourceFigure.svg);
fs.writeFileSync(path.join(out,'figure10-6-coded.svg'),ch.workedExamples.find(e=>e.sourceNumber==='10.4').figure.svg);
fs.writeFileSync(path.join(out,'figure10-7-coded.svg'),ch.topics.find(t=>t.num==='10.5').sourceFigure.svg);
ch.topics.find(t=>t.num==='10.5').sourceShockFigures.forEach((figure,i)=>fs.writeFileSync(path.join(out,`shock-note-${i+1}-coded.svg`),figure.svg));
ch.topics.find(t=>t.num==='10.6').sourceActivityFigures.forEach((figure,i)=>fs.writeFileSync(path.join(out,`water-activity-${i+1}-coded.svg`),figure.svg));
ch.topics.find(t=>t.num==='10.6').sourceWaveFigures.forEach((figure,i)=>fs.writeFileSync(path.join(out,`wave-${i+1}-coded.svg`),figure.svg));
fs.writeFileSync(path.join(out,'figure10-10-coded.svg'),ch.topics.find(t=>t.num==='10.6').sourceSlinkyFigure.svg);
ch.topics.find(t=>t.num==='10.6').sourceParameterFigures.forEach((figure,i)=>fs.writeFileSync(path.join(out,`wave-parameter-${i+1}-coded.svg`),figure.svg));
fs.writeFileSync(path.join(out,'figure10-14-15-ripple-coded.svg'),ch.topics.find(t=>t.num==='10.7').sourceFigure.svg);
fs.writeFileSync(path.join(out,'figure10-16-18-wavefront-coded.svg'),ch.topics.find(t=>t.num==='10.7').sourceFigure.svg);
fs.writeFileSync(path.join(out,'figure10-19-refraction-coded.svg'),ch.topics.find(t=>t.num==='10.7').sourceFigure.svg);
fs.writeFileSync(path.join(out,'figure10-20-diffraction-coded.svg'),ch.topics.find(t=>t.num==='10.7').sourceFigure.svg);
console.log('Exported coded SVGs for local inspection only.');

"""Build a Class 11 textbook (js/<name>_11_book.js) from the page files that book12/engine11.py writes.

    python -X utf8 tools/build_book11.py KEY        (KEY: civics, hpe, ikhtiari, ishist, isl, mq, urdu, cs, chem, bio, stat, eng, phys)

Same page syntax, builder and reader as the Class 6-12 books; registry window.CLS11_BOOKS[<reader's subject key>], rendered by js/cls6_book_reader.js
for classId 'cls11'.  Pages: class-11/KEY/pages/pNNN.txt (one per printed page, book order); output staged in class-11/KEY/build/.
tools/wire_book11.py copies it into js/ and index.html.
"""
from pathlib import Path
import json, sys, datetime

HERE = Path(__file__).resolve().parents[2] / 'class-11'
CLASS12 = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(CLASS12.parent / 'class-6' / 'tools'))
sys.path.insert(0, str(CLASS12 / 'book12'))
import build_math6 as bm  # noqa: E402
import build_book6 as b6  # noqa: E402
import engine11 as E  # noqa: E402

b6.HERE = HERE


def main():
    key = sys.argv[1]
    _, _, view, (name, out_file, glob, title) = E.BOOKS[key]
    bk = E.Book11(key)
    langs = bk.langs()
    total = json.loads((HERE / key / 'meta.json').read_text(encoding='utf-8'))['total']
    titles, starts, labels = b6.load_units(key)
    b = b6.BookBuilder(titles, starts)
    for expected, f in enumerate(sorted((HERE / key / 'pages').glob('p[0-9][0-9][0-9].txt'))):
        if int(f.stem[1:]) != expected:
            raise SystemExit(f'pages must be consecutive: expected p{expected:03}.txt, found {f.name}')
        txt = f.read_text(encoding='utf-8')
        if '@status lesson' in txt:
            b.back_mode = False
        b.page(expected, txt)
    if b.stack:
        print('note: open container carried past last page:', b.stack[-1]['t'])
    solutions = {}

    def extract(list_):
        for x in list_:
            for owner in ([x] if x.get('t') == 'q' else []) + (x.get('parts') or []):
                if owner.get('sol'):
                    sid = f'c11{key}-s{len(solutions) + 1}'
                    solutions[sid] = owner.pop('sol')
                    owner['solId'] = sid
            if x.get('blocks'):
                extract(x['blocks'])
    units = [b.units[n] for n in sorted(b.units)]
    for u in units:
        for s_ in u['sections']:
            extract(s_['blocks'])
    for m in b.ledger:
        m['ocrWordRecall'] = None
        m.pop('english')
    for u in units:
        if u['number'] in labels:
            u['order'], u['number'] = u['number'], labels[u['number']]
        u['reviewStatus'] = {'reviewedPdfPages': len(u['sourcePdfPages'])}
        u.setdefault('exercise', {'source': 'exercises', 'count': len(u.get('exercises') or [])})
        u.setdefault('sloBank', {'source': 'slos'})
        for s in u['sections']:
            paras = [x.get('en', '') for x in s['blocks'] if x['t'] in ('h', 'p')]
            s['heading'] = s['title']
            s['headingUrdu'] = s['titleUrdu']
            s['paras'] = paras
            s['text'] = '\n\n'.join(paras)[:6000]
    reviewed = len(b.ledger)
    book = {'subject': view, 'name': name, 'title': title, 'source': [f'Class 11 {name} (page records)'], 'totalPdfPages': total,
            'reviewedPdfPages': reviewed, 'frontMatter': b.front, 'backMatter': b.back, 'answers': b.answers,
            'answerPdfPages': b.answer_pages, 'complete': reviewed >= total, 'langs': langs, 'tabs': ['lesson', 'exercise']}
    J = lambda o: json.dumps(o, ensure_ascii=False).replace('{{OR}}', '||').replace('{{BAR}}', '|')
    js = [f'// Class 11 {name} (KPTBB) — generated by docs/source-verification/class-12/tools/build_book11.py {key}',
          '// One page per printed page, in book order; edit the data (js/*_11_data.js) and rebuild, not this file.',
          f'const {glob} = ' + J(units) + ';',
          'if (typeof window !== "undefined") {',
          f'  window.{glob} = {glob};',
          '  window.CLS11_BOOKS = window.CLS11_BOOKS || {};',
          f'  window.CLS11_BOOKS[{json.dumps(view)}] = {{units: {glob}, book: ' + J(book) + ', words: {}};',
          '  window.CLS6_SOLUTIONS = Object.assign(window.CLS6_SOLUTIONS || {}, ' + J(solutions) + ');',
          '}', '']
    out = HERE / key / 'build' / out_file
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text('\n'.join(js), encoding='utf-8')
    (HERE / key / 'ledger.json').write_text(json.dumps(b.ledger, ensure_ascii=False, indent=1) + '\n', encoding='utf-8')
    print(f'{key}: {reviewed}/{total} pages; {len(units)} units; answers {len(solutions)}; {out.name} {out.stat().st_size} bytes')


if __name__ == '__main__':
    main()

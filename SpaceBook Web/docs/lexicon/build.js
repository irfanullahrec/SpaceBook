// Builds js/offline_lexicon.js from docs/lexicon/*.txt (rows: en|ur|ps|ar; alternatives separated by "،" or ",").
const fs = require('fs');
const rows = [];
for (const f of fs.readdirSync(__dirname).filter(f => /^(en|ur|ps|ar)\d+\.txt$/.test(f)).sort())
  for (const line of fs.readFileSync(__dirname + '/' + f, 'utf8').split('\n')) {
    const p = line.split('|').map(x => x.trim()); if (p.length !== 4 || !p.join('')) continue; rows.push(p.join('|'));
  }
const out = '/* Generated by docs/lexicon/build.js — offline word meanings (English | Urdu | Pashto | Arabic) for the\n * most frequent project words, used by universal_translate.js and the word hover card without internet. */\n' +
  'window.SB_OFFLINE_LEXICON = ' + JSON.stringify(rows.join('\n')) + ';\n';
fs.writeFileSync(__dirname + '/../../js/offline_lexicon.js', out);
console.log('rows', rows.length, 'bytes', out.length);
